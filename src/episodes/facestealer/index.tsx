import { defineEpisode, Timeline } from '../../engine';
import timeline from './timeline.json';
import words from './words.json';
import defs from './defs.json';
import { buildShots, Def } from './scenes';

// "FaceStealer: The Fake Video Call Scam" (v2, ~4 min). A landscape (1920 x 1080) explainer built from the FBI FLASH
// AC-111226-MS and DOJ press release 26-1356 (both 12 Nov 2026). Quotes are shown on crops of those pages with the
// exact words highlighted, and set large beneath. All people shown are original stick-figure avatars; no real person or
// brand UI is imitated. The timeline, captions and shot list are generated by research/facestealer/v2/plan_v2.py.

type W = { w: string; s: number; e: number; p?: string };

export const facestealer = defineEpisode('FaceStealer', {
  timeline: timeline as Timeline,
  bg: '#060912',
  captions: words as W[],
  // Captions sit in a band below y = 880 that the scenes keep clear: a dark plate, balanced 1-4 word chunks (22 chars max), gone in pauses.
  capY: 0.905,
  capStyle: { size: 64, maxWords: 4, maxChars: 22, plate: true, lead: 0.05, hold: 0.35, minShow: 0.4, bounce: 0.08, tilt: 0, gap: 18, balance: true },
  xfade: 6,
  shots: buildShots(defs as Def[]),
});
